//! The command surface, listed once. `main.rs` registers it on the real window system and the
//! `flywheel-headless` binary (feature `headless`) on a mock runtime for the end-to-end harness,
//! so the one list is what both expose: a command added here reaches the shell and the harness
//! together, and cannot reach one without the other.
//!
//! This list is the enforcement point for the app's command surface: a #[tauri::command] is
//! reachable from the webview only if it is named here. The roster string in
//! `capabilities/default.json` is documentation, not enforcement. Adding a command means adding it
//! here; `tests/handler_roster.rs` fails the build if the two drift in either direction (a command
//! declared but not listed, or an entry naming no command).
//!
//! A macro rather than a function because `generate_handler!` takes literal paths, and the paths
//! are read at the call site: the caller needs `commands` in scope.

