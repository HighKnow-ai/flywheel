function makeSummary(overrides: Partial<Record<string, unknown>> = {}) {
  return {
    agentRunId: "run-1",
    createdAt: "2026-01-01T00:00:00.000Z",
    autoGenerated: false,
    changedFiles: ["src/a.ts"],
    changedProse: "Did a thing.",
    remains: "Nothing.",
    nextSessionMustKnow: "Watch out for X.",
    decisions: [{ id: "d1", statement: "Chose approach A" }],
    folded: false,
    ...overrides,
  };
}

function makeCompaction(overrides: Partial<Record<string, unknown>> = {}) {
  return {
    total: 0,
    foldedCount: 0,
    verbatimCount: 0,
    foldedRange: null,
    verbatimRange: null,
    sentence: null,
    ...overrides,
  };
}

function makePacket(overrides: Partial<Record<string, unknown>> = {}) {
  return {
    taskKey: "FLY-42",
    taskTitle: "Wire the launch sheet",
    taskDescription: "Some task description",
    epicTitle: "Ship phase 2",
    epicDescription: "Epic description",
    criteria: [{ statement: "Does the thing", verificationHint: "run the test" }],
    summaries: [],
    compaction: makeCompaction(),
    decisions: [],
    drift: [],
    branch: "flywheel/fly-42-wire-the-launch-sheet",
    baseRef: "main",
    worktreePath: "/Users/dev/Flywheel/FLY/FLY-42",
    diff: null,
    renderedPrompt: "# Wire the launch sheet",
    ...overrides,
  };
}

function makeEpicPacket(overrides: Partial<Record<string, unknown>> = {}) {
  return {
    epic: { key: "FLY-9", title: "Ship the thing", description: "Epic body", status: "backlog" },
    taskRoster: [],
    answeredAssumptions: [],
    rejected: { verbatim: [], folded: [], boundary: { total: 0, verbatimCount: 0, foldedCount: 0, boundarySentence: null } },
    priorAuthoringRuns: [],
    renderedPrompt: "## Epic\n\nShip the thing\n",
    ...overrides,
  };
}

function renderSheet(props: Partial<React.ComponentProps<typeof LaunchSheet>> = {}) {
  const queryClient = new QueryClient();
  const onClose = props.onClose ?? vi.fn();
  const onStarted = props.onStarted ?? vi.fn();
  const utils = render(
    <QueryClientProvider client={queryClient}>
      <LaunchSheet taskId={props.taskId ?? "task-1"} onClose={onClose} onStarted={onStarted} />
    </QueryClientProvider>,
  );
  return { ...utils, onClose, onStarted };
}

