/**
 * Behavior under test (plan 02-04 Task 3, acceptance criteria): the header/placeholder/mode
 * labels, Cancel/Escape leaving the start command uncalled, the Enter/⌘Enter contract inside vs.
 * outside the free-text field, an empty instruction still submitting, and the sizing contract.
 */
import { describe, expect, it, vi } from "vitest";
import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { LaunchSheet } from "../LaunchSheet";

const previewMock = vi.fn();
const startMock = vi.fn();

vi.mock("../../adapters/tauri", async () => {
  const actual = await vi.importActual<typeof import("../../adapters/tauri")>("../../adapters/tauri");
  return {
    ...actual,
    previewContextPacket: (taskId: string) => previewMock(taskId),
    startAgentRun: (taskId: string, permissionMode: string, instruction?: string) =>
      startMock(taskId, permissionMode, instruction),
  };
});

function makeSummary(overrides: Partial<Record<string, unknown>> = {}) {
  return {
    agentRunId: "run-1",
    createdAt: "2026-01-01T00:00:00.000Z",
    autoGenerated: false,
    changedFiles: ["src/a.ts"],
    changedProse: "Did a thing.",
    remains: "Nothing.",
    nextSessionMustKnow: "Watch out for X.",
    decisions: [{ id: "d1", statement: "Chose approach A" }],
    folded: false,
    ...overrides,
  };
}

function makeCompaction(overrides: Partial<Record<string, unknown>> = {}) {
  return {
    total: 0,
    foldedCount: 0,
    verbatimCount: 0,
    foldedRange: null,
    verbatimRange: null,
    sentence: null,
    ...overrides,
  };
}

function makePacket(overrides: Partial<Record<string, unknown>> = {}) {
  return {
    taskKey: "FLY-42",
    taskTitle: "Wire the launch sheet",
    taskDescription: "Some task description",
    epicTitle: "Ship phase 2",
    epicDescription: "Epic description",
    criteria: [{ statement: "Does the thing", verificationHint: "run the test" }],
    summaries: [],
    compaction: makeCompaction(),
    decisions: [],
    branch: "flywheel/fly-42-wire-the-launch-sheet",
    baseRef: "main",
    worktreePath: "/Users/dev/Flywheel/FLY/FLY-42",
    diff: null,
    renderedPrompt: "# Wire the launch sheet",
    ...overrides,
  };
}

function renderSheet(props: Partial<React.ComponentProps<typeof LaunchSheet>> = {}) {
  const queryClient = new QueryClient();
  const onClose = props.onClose ?? vi.fn();
  const onStarted = props.onStarted ?? vi.fn();
  const utils = render(
    <QueryClientProvider client={queryClient}>
      <LaunchSheet taskId={props.taskId ?? "task-1"} onClose={onClose} onStarted={onStarted} />
    </QueryClientProvider>,
  );
  return { ...utils, onClose, onStarted };
}

describe("LaunchSheet", () => {
  it("renders the exact header once the preview resolves", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset();
    renderSheet();

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());
  });

  it("shows the free-text field's exact placeholder", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset();
    renderSheet();

    await waitFor(() =>
      expect(
        screen.getByPlaceholderText("Anything else the agent should know for this run? (optional)"),
      ).toBeInTheDocument(),
    );
  });

  it("renders the four mode labels with Accept Edits selected by default", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset();
    renderSheet();

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    const acceptEdits = screen.getByRole("radio", { name: "Accept Edits" });
    const plan = screen.getByRole("radio", { name: "Plan" });
    const askEveryTime = screen.getByRole("radio", { name: "Ask Every Time" });
    const bypass = screen.getByRole("radio", { name: "Bypass Permissions" });

    expect(acceptEdits).toBeInTheDocument();
    expect(plan).toBeInTheDocument();
    expect(askEveryTime).toBeInTheDocument();
    expect(bypass).toBeInTheDocument();
    expect(acceptEdits).toHaveAttribute("aria-checked", "true");
    expect(plan).toHaveAttribute("aria-checked", "false");
  });

  it.each([
    ["Accept Edits", "acceptEdits"],
    ["Plan", "plan"],
    ["Ask Every Time", "default"],
    ["Bypass Permissions", "bypassPermissions"],
  ])("submits %s as the adapter value %s, with no relabeling", async (label, value) => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset().mockResolvedValue({ id: "run-1", taskId: "task-1", status: "running", permissionMode: value });
    renderSheet();

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    fireEvent.click(screen.getByRole("radio", { name: label }));
    fireEvent.click(screen.getByRole("button", { name: "Start Work" }));

    await waitFor(() => expect(startMock).toHaveBeenCalledTimes(1));
    expect(startMock).toHaveBeenCalledWith("task-1", value, "");
  });

  it("Cancel leaves the start command uncalled", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset();
    const onClose = vi.fn();
    renderSheet({ onClose });

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    fireEvent.click(screen.getByRole("button", { name: "Cancel" }));

    expect(onClose).toHaveBeenCalledTimes(1);
    expect(startMock).not.toHaveBeenCalled();
  });

  it("Escape leaves the start command uncalled", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset();
    const onClose = vi.fn();
    renderSheet({ onClose });

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    fireEvent.keyDown(screen.getByRole("dialog"), { key: "Escape" });

    expect(onClose).toHaveBeenCalledTimes(1);
    expect(startMock).not.toHaveBeenCalled();
  });

  it("Enter with focus in the body submits", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset().mockResolvedValue({ id: "run-1", taskId: "task-1", status: "running", permissionMode: "acceptEdits" });
    renderSheet();

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    fireEvent.keyDown(screen.getByRole("dialog"), { key: "Enter" });

    await waitFor(() => expect(startMock).toHaveBeenCalledTimes(1));
  });

  it("Enter with focus in the free-text field does not submit, but ⌘Enter does", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset().mockResolvedValue({ id: "run-1", taskId: "task-1", status: "running", permissionMode: "acceptEdits" });
    renderSheet();

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    const field = screen.getByLabelText("Instruction");
    fireEvent.keyDown(field, { key: "Enter" });
    expect(startMock).not.toHaveBeenCalled();

    fireEvent.keyDown(field, { key: "Enter", metaKey: true });
    await waitFor(() => expect(startMock).toHaveBeenCalledTimes(1));
  });

  it("submitting with an empty instruction still calls the start command", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset().mockResolvedValue({ id: "run-1", taskId: "task-1", status: "running", permissionMode: "acceptEdits" });
    renderSheet();

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    fireEvent.click(screen.getByRole("button", { name: "Start Work" }));

    await waitFor(() => expect(startMock).toHaveBeenCalledTimes(1));
    expect(startMock).toHaveBeenCalledWith("task-1", "acceptEdits", "");
  });

  it("renders the sheet at 640px wide with an 80vh maximum height", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket());
    startMock.mockReset();
    renderSheet();

    const dialog = await screen.findByRole("dialog");
    expect(dialog).toHaveStyle("width: 640px");
    // `toHaveStyle` compares jsdom's RESOLVED computed style, which turns a relative unit like
    // `80vh` into a viewport-dependent pixel value — reading the raw inline style declaration
    // directly is what actually asserts the specified `80vh`, not an incidental resolved number.
    expect(dialog.style.maxHeight).toBe("80vh");
  });

  it("renders nothing when taskId is null", () => {
    previewMock.mockReset();
    startMock.mockReset();
    const queryClient = new QueryClient();
    const { container } = render(
      <QueryClientProvider client={queryClient}>
        <LaunchSheet taskId={null} onClose={() => {}} onStarted={() => {}} />
      </QueryClientProvider>,
    );
    expect(container).toBeEmptyDOMElement();
    expect(previewMock).not.toHaveBeenCalled();
  });
});

describe("LaunchSheet — Prior Sessions, compaction boundary, diff so far (plan 04-09)", () => {
  it("renders four folded entries, the boundary sentence and five verbatim entries for nine summaries, with folded prose absent", async () => {
    const summaries = Array.from({ length: 9 }, (_, i) => {
      const ordinal = i + 1;
      return makeSummary({
        agentRunId: `run-${ordinal}`,
        folded: i < 4,
        changedFiles: [`src/file-${ordinal}.ts`],
        changedProse: i < 4 ? `FOLDED-PROSE-${ordinal}` : `VERBATIM-PROSE-${ordinal}`,
        decisions: [{ id: `d${ordinal}`, statement: `Decision ${ordinal}` }],
      });
    });
    previewMock.mockReset().mockResolvedValue(
      makePacket({
        summaries,
        compaction: makeCompaction({
          total: 9,
          foldedCount: 4,
          verbatimCount: 5,
          foldedRange: [1, 4],
          verbatimRange: [5, 9],
          sentence: "Sessions 1-4 are summarized above; sessions 5-9 are shown in full.",
        }),
      }),
    );
    startMock.mockReset();
    renderSheet();

    await waitFor(() => expect(screen.getByText("Session 1")).toBeInTheDocument());

    expect(screen.getByText("Earlier sessions (folded)")).toBeInTheDocument();
    expect(screen.getByText("Recent sessions (verbatim)")).toBeInTheDocument();
    expect(
      screen.getByText("Sessions 1-4 are summarized above; sessions 5-9 are shown in full."),
    ).toBeInTheDocument();
    expect(screen.getAllByText(/^Session \d$/)).toHaveLength(9);

    // Folded entries: decisions survive, prose does not.
    expect(screen.getByText("Decision 1")).toBeInTheDocument();
    expect(screen.queryByText(/FOLDED-PROSE-/)).not.toBeInTheDocument();

    // Verbatim entries: full prose renders.
    expect(screen.getByText("VERBATIM-PROSE-5")).toBeInTheDocument();
  });

  it("renders no boundary marker and no fold-subsection headings for four summaries", async () => {
    const summaries = Array.from({ length: 4 }, (_, i) =>
      makeSummary({ agentRunId: `run-${i + 1}`, folded: false }),
    );
    previewMock.mockReset().mockResolvedValue(
      makePacket({
        summaries,
        compaction: makeCompaction({ total: 4, foldedCount: 0, verbatimCount: 4, sentence: null }),
      }),
    );
    startMock.mockReset();
    renderSheet();

    await waitFor(() => expect(screen.getByText("Session 1")).toBeInTheDocument());

    expect(screen.queryByText("Earlier sessions (folded)")).not.toBeInTheDocument();
    expect(screen.queryByText("Recent sessions (verbatim)")).not.toBeInTheDocument();
  });

  it("renders the auto-generated label for a synthesized summary and not for an agent-authored one", async () => {
    previewMock.mockReset().mockResolvedValue(
      makePacket({
        summaries: [
          makeSummary({ agentRunId: "run-auto", autoGenerated: true, folded: false }),
          makeSummary({ agentRunId: "run-agent", autoGenerated: false, folded: false }),
        ],
        compaction: makeCompaction({ total: 2, foldedCount: 0, verbatimCount: 2 }),
      }),
    );
    startMock.mockReset();
    renderSheet();

    await waitFor(() => expect(screen.getByText("Session 1")).toBeInTheDocument());

    expect(screen.getAllByText("auto-generated")).toHaveLength(1);
  });

  it("renders no diff section when packet.diff is null", async () => {
    previewMock.mockReset().mockResolvedValue(makePacket({ diff: null }));
    startMock.mockReset();
    renderSheet();

    await waitFor(() => expect(screen.getByText("Start Work on FLY-42")).toBeInTheDocument());

    expect(screen.queryByText("Diff So Far")).not.toBeInTheDocument();
  });

  it("renders the porcelain row for a dirty working tree file", async () => {
    previewMock.mockReset().mockResolvedValue(
      makePacket({
        diff: {
          baseRef: "main",
          committedStat: "",
          committedPaths: [],
          workingTreePorcelain: " M src/dirty.ts\n",
        },
      }),
    );
    startMock.mockReset();
    renderSheet();

    await waitFor(() => expect(screen.getByText("Diff So Far")).toBeInTheDocument());

    expect(screen.getByText("M src/dirty.ts")).toBeInTheDocument();
    expect(screen.queryByText(/Committed since/)).not.toBeInTheDocument();
    expect(screen.getByText("You are in this worktree — read any of these files directly for the full detail.")).toBeInTheDocument();
  });
});
