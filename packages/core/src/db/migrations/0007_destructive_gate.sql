-- D-56/D-57 (plan 03-07): `permission_requests.destructive_category` — the column the
-- destructive-action gate card's variant selection (plan 03-12) reads, and the column
-- `answer_request`'s allow-always guard checks before ever granting a standing permission-rules
-- grant (D-57's "structurally absent, not merely discouraged," enforced at the write path).
--
-- A plain `ALTER TABLE ... ADD COLUMN`, not a table rebuild: SQLite can add a column to an
-- existing table without recreating it, unlike `0006_recovery_statuses.sql`'s CHECK-constraint
-- changes (which DO require a rebuild, since SQLite cannot ALTER a CHECK constraint in place).
-- Nullable, no default — NULL means "the routine permission-request variant," matching every
-- pre-migration row and every future non-destructive request.
--
-- SQLite's `ALTER TABLE ... ADD COLUMN` cannot attach a CHECK constraint to an existing table, so
-- this migration does NOT attempt to constrain the column's vocabulary in SQL. That vocabulary
-- (the eight `DestructiveCategory` names, `packages/core/src/destructive.rs`) is instead enforced
-- in Rust, at the one write path that ever sets this column
-- (`domain::permission_request::create_pending_request`), which `bail!`s on any value outside
-- `DestructiveCategory::as_str()`'s full set before its transaction opens. This is a deliberate,
-- narrow departure from this codebase's "the schema, not app code, is the authority" rule
-- (`0002_board_schema.sql`'s five-state workflow CHECK, `0004_permission_gate.sql`'s own
-- `permission_requests.status` CHECK) — bounded here because there is exactly one writer of this
-- column in the whole workspace, and that writer is Rust-only application code, never a
-- hand-crafted SQL statement a future migration or tool could bypass.
ALTER TABLE permission_requests ADD COLUMN destructive_category TEXT;
