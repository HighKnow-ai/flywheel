//! FNC-01: the three spine tables cannot erode while records are added above them. This pins,
//! against the post-0023 schema (D-14, the `estimate` column is already gone):
//! - the normalised `CREATE TABLE` text of `epics`, `tasks` and `issues`, read from `sqlite_master`
//!   on a migrated database, so the pin covers any migration path that reaches those tables;
//! - the foreign-key parents of `epics`, so a new table above the epic fails the build until the
//!   declared chain is edited in the same diff.
//!
//! If a change to one of these is intended, edit the pin in the same diff. That is the point.
//!
//! Self-contained: carries its own scratch-database helper rather than sharing one.

use core::db::open_and_migrate;
use rusqlite::Connection;

/// Generated by reading `sqlite_master` on a migrated database and passing it through
/// [`normalise_ddl`], not hand-transcribed from the migration text. `"epics"` and `"tasks"` are
/// quoted because migration 0023 built them by `RENAME`; `issues` was never rebuilt.
const EPICS_DDL_PIN: &str =
    r#"CREATE TABLE "epics" ( id TEXT PRIMARY KEY NOT NULL CHECK (length(id) = 26), project_id TEXT NOT NULL REFERENCES projects(id), key TEXT NOT NULL, title TEXT NOT NULL, description TEXT, status TEXT NOT NULL CHECK (status IN ('backlog', 'todo', 'in_progress', 'in_review', 'done')), rank TEXT NOT NULL, priority INTEGER NOT NULL CHECK (priority BETWEEN 0 AND 4), assignee_id TEXT REFERENCES actors(id), integration_branch TEXT, archived_at TEXT, created_by TEXT NOT NULL REFERENCES actors(id), created_at TEXT NOT NULL, updated_at TEXT NOT NULL )"#;

const TASKS_DDL_PIN: &str =
    r#"CREATE TABLE "tasks" ( id TEXT PRIMARY KEY NOT NULL CHECK (length(id) = 26), project_id TEXT NOT NULL REFERENCES projects(id), epic_id TEXT REFERENCES epics(id), key TEXT NOT NULL, title TEXT NOT NULL, description TEXT, status TEXT NOT NULL CHECK (status IN ('backlog', 'todo', 'in_progress', 'in_review', 'done')), rank TEXT NOT NULL, priority INTEGER NOT NULL CHECK (priority BETWEEN 0 AND 4), assignee_id TEXT REFERENCES actors(id), created_by TEXT NOT NULL REFERENCES actors(id), created_at TEXT NOT NULL, updated_at TEXT NOT NULL )"#;

const ISSUES_DDL_PIN: &str =
    r#"CREATE TABLE issues ( id TEXT PRIMARY KEY NOT NULL CHECK (length(id) = 26), project_id TEXT NOT NULL REFERENCES projects(id), epic_id TEXT REFERENCES epics(id), task_id TEXT REFERENCES tasks(id), key TEXT NOT NULL, title TEXT NOT NULL, body TEXT, kind TEXT NOT NULL CHECK (kind IN ('bug', 'idea', 'question', 'risk')), rank TEXT NOT NULL, created_by TEXT NOT NULL REFERENCES actors(id), created_at TEXT NOT NULL, updated_at TEXT NOT NULL )"#;

/// (column, parent table) pairs `pragma_foreign_key_list('epics')` reports, sorted by column.
const FOREIGN_KEY_PARENTS_ABOVE_EPICS: &[(&str, &str)] =
    &[("assignee_id", "actors"), ("created_by", "actors"), ("project_id", "projects")];

/// Strip SQL line comments, collapse every run of whitespace to one space, trim. A comment or an
/// indentation change in a migration file is not a build failure; any column, type, `CHECK`,
/// `DEFAULT` or `REFERENCES` change is.
fn normalise_ddl(sql: &str) -> String {
    let without_comments: Vec<&str> = sql
        .lines()
        .map(|line| line.find("--").map_or(line, |at| &line[..at]))
        .collect();
    without_comments.join(" ").split_whitespace().collect::<Vec<_>>().join(" ")
}

fn migrated_scratch_db() -> (Connection, tempfile::TempDir) {
    let dir = tempfile::tempdir().expect("failed to create scratch dir");
    let conn = open_and_migrate(&dir.path().join("flywheel.db"), &dir.path().join("backups"))
        .expect("open_and_migrate should succeed");
    (conn, dir)
}

fn normalised_table_ddl(conn: &Connection, table: &str) -> String {
    let sql: String = conn
        .query_row("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?1", [table], |row| {
            row.get(0)
        })
        .unwrap_or_else(|e| panic!("sqlite_master should hold a CREATE TABLE for {table}: {e}"));
    normalise_ddl(&sql)
}

fn diff_message(table: &str, pinned: &str, actual: &str) -> String {
    format!(
        "FNC-01: the DDL of `{table}` no longer matches its pin.\n  pinned: {pinned}\n  actual: {actual}\n\
         If this change is intended, edit the pin in the same diff."
    )
}

#[test]
fn the_spine_ddl_is_pinned() {
    let (conn, _dir) = migrated_scratch_db();
    for (table, pinned) in [("epics", EPICS_DDL_PIN), ("tasks", TASKS_DDL_PIN), ("issues", ISSUES_DDL_PIN)] {
        let actual = normalised_table_ddl(&conn, table);
        assert_eq!(pinned, actual, "{}", diff_message(table, pinned, &actual));
    }
}

#[test]
fn the_spine_pin_fires_on_a_planted_ddl_change() {
    let (conn, _dir) = migrated_scratch_db();
    // `ALTER TABLE ... ADD COLUMN` is legal on `issues`, and this scratch database is discarded.
    conn.execute_batch("ALTER TABLE issues ADD COLUMN planted TEXT").expect("planting a column should succeed");
    assert_ne!(
        ISSUES_DDL_PIN,
        normalised_table_ddl(&conn, "issues"),
        "the pin did not notice an added column, so it would not notice an erosion either"
    );
}

#[test]
fn normalisation_ignores_comments_and_whitespace_but_not_a_column() {
    let base = normalise_ddl("CREATE TABLE t (\n    a TEXT, -- why a\n    b INTEGER\n)");
    assert_eq!(base, normalise_ddl("CREATE TABLE t ( a TEXT,   b INTEGER )"));
    assert_ne!(base, normalise_ddl("CREATE TABLE t ( a TEXT, b INTEGER, c TEXT )"));
}

/// The parent chain above `epics` is pinned: adding a parent (a new foreign key on `epics`) fails
/// this test until `FOREIGN_KEY_PARENTS_ABOVE_EPICS` is edited in the same diff.
///
/// Phase 13 success criterion 1 says the chain above `epics` ends at the cycle table, which has no
/// parent and which no other table references. That clause cannot be satisfied yet: the `cycles`
/// table does not exist until Phase 14 (its schema and column allowlist are Phase 14 success
/// criterion 1), so the chain above `epics` ends at `projects` today. The mechanism criterion 1
/// needs is complete here: when Phase 14 adds `cycles` and an `epics.cycle_id` foreign key, this
/// test fails until the const is edited in the same diff, and the "no parent, no other table
/// references it" half is then two assertions added beside this one.
#[test]
fn the_parent_chain_above_epics_is_pinned() {
    let (conn, _dir) = migrated_scratch_db();
    let mut stmt = conn
        .prepare("SELECT \"from\", \"table\" FROM pragma_foreign_key_list('epics') ORDER BY \"from\"")
        .expect("pragma_foreign_key_list should prepare");
    let actual: Vec<(String, String)> = stmt
        .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))
        .expect("pragma_foreign_key_list should run")
        .collect::<Result<_, _>>()
        .expect("pragma_foreign_key_list rows should read");
    let pinned: Vec<(String, String)> = FOREIGN_KEY_PARENTS_ABOVE_EPICS
        .iter()
        .map(|(column, parent)| (column.to_string(), parent.to_string()))
        .collect();
    assert_eq!(
        pinned, actual,
        "FNC-01: the foreign-key parents of `epics` changed. If this is intended, edit \
         FOREIGN_KEY_PARENTS_ABOVE_EPICS in the same diff."
    );
}
